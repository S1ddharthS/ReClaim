import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright-core';

const site = process.env.JIRA_BASE_URL || 'https://sjec-team-xyntwxhy.atlassian.net';
const email = process.env.JIRA_EMAIL || '24c52.siddharth@sjec.ac.in';
const cdpUrl = process.env.JIRA_CDP_URL || 'http://127.0.0.1:9223';
const outFile = path.resolve(import.meta.dirname, '..', '.env');

const browser = await chromium.connectOverCDP(cdpUrl);
const context = browser.contexts()[0];
if (!context) throw new Error('No browser context found over CDP.');
const cookies = await context.cookies(site);
const byName = new Map(cookies.map((cookie) => [cookie.name, cookie.value]));

const session = byName.get('tenant.session.token');
if (!session) {
  throw new Error(
    'tenant.session.token is missing. Sign in to Jira in the attached browser and run this script again.'
  );
}

const keep = ['tenant.session.token', 'atlassian.xsrf.token', 'JSESSIONID', 'ajs_anonymous_id'];
const pairs = keep
  .filter((name) => byName.has(name))
  .map((name) => `${name}=${byName.get(name)}`);
const cookieHeader = pairs.join('; ');
const xsrf = byName.get('atlassian.xsrf.token') || '';

const lines = [
  '# Generated by automation/export-cookies.mjs from the authenticated browser session.',
  '# Do not commit this file. Cookies expire; re-run the exporter when Jira returns 401/403.',
  `JIRA_BASE_URL=${site}`,
  `JIRA_EMAIL=${email}`,
  `JIRA_COOKIE=${cookieHeader}`,
  `JIRA_XSRF_TOKEN=${xsrf}`,
  'JIRA_PROJECT_KEY=RECL',
  '',
];
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`Wrote ${outFile}`);
console.log(`Cookies captured: ${pairs.map((pair) => pair.split('=')[0]).join(', ')}`);
console.log(`Cookie header length: ${cookieHeader.length}`);

await browser.close();
